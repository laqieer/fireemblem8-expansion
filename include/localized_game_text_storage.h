#ifndef GUARD_LOCALIZED_GAME_TEXT_STORAGE_H
#define GUARD_LOCALIZED_GAME_TEXT_STORAGE_H

#include "localized_game_text.h"

#if FE8_LOCALIZED_GAME_TEXT_CJK_PROFILE_ENABLED
#include "localized_game_text_data.h"

#define FE8_LOCALIZED_GAME_TEXT_REQUIRED_STORAGE_BYTES \
    ((FE8_GAME_LOCALIZATION_MAX_DECODED_BYTES) \
        > FE8_LOCALIZED_GAME_TEXT_TARGET_CAPACITY \
        ? (FE8_GAME_LOCALIZATION_MAX_DECODED_BYTES) \
        : FE8_LOCALIZED_GAME_TEXT_TARGET_CAPACITY)

#define FE8_LOCALIZED_GAME_TEXT_MSG_BUFFER_BYTES \
    FE8_LOCALIZED_GAME_TEXT_REQUIRED_STORAGE_BYTES

struct MsgBuffer
{
    union
    {
        struct
        {
            u8 buffer1[FE8_LOCALIZED_GAME_TEXT_LEGACY_BUFFER1_BYTES];
            u8 buffer2[FE8_LOCALIZED_GAME_TEXT_LEGACY_BUFFER2_BYTES];
            u8 buffer3[FE8_LOCALIZED_GAME_TEXT_LEGACY_BUFFER3_BYTES];
            u8 buffer4[FE8_LOCALIZED_GAME_TEXT_LEGACY_BUFFER4_BYTES];
            u8 buffer5[FE8_LOCALIZED_GAME_TEXT_LEGACY_BUFFER5_BYTES];
        } legacy;
        u8 localized[FE8_LOCALIZED_GAME_TEXT_REQUIRED_STORAGE_BYTES];
    } storage;
};

LOCALIZED_GAME_TEXT_STATIC_ASSERT(
    FE8_LOCALIZED_GAME_TEXT_REQUIRED_STORAGE_BYTES >= FE8_GAME_LOCALIZATION_MAX_DECODED_BYTES,
    generated_max_fits_storage);
#endif

#endif
